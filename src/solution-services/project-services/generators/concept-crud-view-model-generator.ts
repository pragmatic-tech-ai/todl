/**
 * Emits `src/ui/<Class>/<Class>-vm.ts`: the TypeScript view-models that back the
 * Task-5 list.mu / form.mu. Two classes per concept:
 *   - `<Class>VM` (default export) — the ROW/record VM list rows and `$Selected`
 *     bind to: a two-way property per scalar field plus `ToWriteOp()`.
 *   - `<Class>ListVM` — the CONTAINER: `Items`, `Selected`, `ErrorText`, and the
 *     `New`/`Save`/`Delete` `RelayCommand`s wired through `ModelDataSource.Apply`.
 * The emitted file is generated content in the app's own style; this generator
 * source obeys repo style.
 */

import { WritePolicy, type GeneratorResult } from "./project-content-generator.js";
import { ConceptUiGeneratorSupport, type ConceptGeneratorContext, type IConceptUiGenerator } from "./concept-ui-generator.js";
import { UiFieldType, type ConceptUiModel, type UiField } from "./concept-ui-model.js";

export class ConceptCrudViewModelGenerator implements IConceptUiGenerator
{
    private static readonly GeneratorId = "concept-crud-view-model";
    private static readonly PathTemplate = "src/ui/{0}/{0}-vm.ts";
    private static readonly ClassPlaceholder = "{0}";

    private static readonly ClassToken = "{Class}";
    private static readonly ConceptToken = "{Concept}";
    private static readonly BindingToken = "{Binding}";
    private static readonly NameToken = "{Name}";
    private static readonly SeedsToken = "{seeds}";
    private static readonly PropsToken = "{props}";
    private static readonly FieldsToken = "{fields}";

    private static readonly Eol = "\n";

    private static readonly SnapshotLine = "        const snapshot = entity.Snapshot();";
    private static readonly SeedTemplate = "        vm.values[\"{Name}\"] = snapshot[\"{Name}\"];";
    private static readonly FieldEntryTemplate = "                \"{Name}\": this.{Binding},";

    private static readonly StringPropTemplate = [
        "    public get {Binding}(): string",
        "    {",
        "        return (this.values[\"{Name}\"] as string) ?? \"\";",
        "    }",
        "",
        "    public set {Binding}(value: string)",
        "    {",
        "        const old = this.values[\"{Name}\"];",
        "        this.values[\"{Name}\"] = value;",
        "        this.RaisePropertyChanged(\"{Binding}\", old, value);",
        "    }",
    ].join(ConceptCrudViewModelGenerator.Eol);

    private static readonly NumberPropTemplate = [
        "    public get {Binding}(): number",
        "    {",
        "        return (this.values[\"{Name}\"] as number) ?? 0;",
        "    }",
        "",
        "    public set {Binding}(value: number)",
        "    {",
        "        const old = this.values[\"{Name}\"];",
        "        this.values[\"{Name}\"] = Number(value);",
        "        this.RaisePropertyChanged(\"{Binding}\", old, this.values[\"{Name}\"]);",
        "    }",
    ].join(ConceptCrudViewModelGenerator.Eol);

    private static readonly BooleanPropTemplate = [
        "    public get {Binding}(): boolean",
        "    {",
        "        return (this.values[\"{Name}\"] as boolean) ?? false;",
        "    }",
        "",
        "    public set {Binding}(value: boolean)",
        "    {",
        "        const old = this.values[\"{Name}\"];",
        "        this.values[\"{Name}\"] = value;",
        "        this.RaisePropertyChanged(\"{Binding}\", old, value);",
        "    }",
    ].join(ConceptCrudViewModelGenerator.Eol);

    private static readonly FileTemplate = [
        "// Generated by @pragmatic-tech-ai/todl. Do not edit.",
        "import { Observable, RelayCommand } from \"@pragmatic-tech-ai/mural/runtime\";",
        "import { ConnectorWriteOpKind, ConnectorWriteStatus } from \"@pragmatic-tech-ai/todl\";",
        "import type { ConnectorWriteOp, ModelDataSource, ReflectedEntity } from \"@pragmatic-tech-ai/todl\";",
        "",
        "export default class {Class}VM extends Observable",
        "{",
        "    public static readonly Concept = \"{Concept}\";",
        "",
        "    public IsNew: boolean = false;",
        "    public Id: string | undefined = undefined;",
        "    private readonly values: Record<string, unknown> = {};",
        "",
        "    public static FromEntity(entity: ReflectedEntity): {Class}VM",
        "    {",
        "        const vm = new {Class}VM();",
        "        vm.Id = entity.id;",
        "{seeds}",
        "        return vm;",
        "    }",
        "",
        "{props}",
        "    public ToWriteOp(): ConnectorWriteOp",
        "    {",
        "        return {",
        "            Kind: this.IsNew ? ConnectorWriteOpKind.Create : ConnectorWriteOpKind.Update,",
        "            Concept: {Class}VM.Concept,",
        "            Id: this.Id,",
        "            Fields:",
        "            {",
        "{fields}",
        "            },",
        "        };",
        "    }",
        "}",
        "",
        "export class {Class}ListVM extends Observable",
        "{",
        "    private items: readonly {Class}VM[] = [];",
        "    private selected: {Class}VM | undefined = undefined;",
        "    private errorText: string = \"\";",
        "",
        "    public readonly NewCommand: RelayCommand;",
        "    public readonly SaveCommand: RelayCommand;",
        "    public readonly DeleteCommand: RelayCommand;",
        "",
        "    public constructor(private readonly model: ModelDataSource)",
        "    {",
        "        super();",
        "        this.RebuildItems();",
        "        this.NewCommand = new RelayCommand(() => this.New());",
        "        this.SaveCommand = new RelayCommand(() => this.Save());",
        "        this.DeleteCommand = new RelayCommand(() => this.Delete());",
        "        // Remote data arrives asynchronously; the model emits DataChanged after each",
        "        // materialization (Prepare / Refresh / load), so re-read when the live data lands.",
        "        this.model.DataChanged.subscribe(() => this.OnDataChanged());",
        "    }",
        "",
        "    public get Items(): readonly {Class}VM[]",
        "    {",
        "        return this.items;",
        "    }",
        "",
        "    public get Selected(): {Class}VM | undefined",
        "    {",
        "        return this.selected;",
        "    }",
        "",
        "    public set Selected(value: {Class}VM | undefined)",
        "    {",
        "        const old = this.selected;",
        "        this.selected = value;",
        "        this.RaisePropertyChanged(\"Selected\", old, value);",
        "    }",
        "",
        "    public get ErrorText(): string",
        "    {",
        "        return this.errorText;",
        "    }",
        "",
        "    public set ErrorText(value: string)",
        "    {",
        "        const old = this.errorText;",
        "        this.errorText = value;",
        "        this.RaisePropertyChanged(\"ErrorText\", old, value);",
        "    }",
        "",
        "    private New(): void",
        "    {",
        "        const blank = new {Class}VM();",
        "        blank.IsNew = true;",
        "        this.Selected = blank;",
        "    }",
        "",
        "    private async Save(): Promise<void>",
        "    {",
        "        if (this.selected === undefined)",
        "        {",
        "            return;",
        "        }",
        "        const savedId = this.selected.Id;",
        "        const result = await this.model.Apply([this.selected.ToWriteOp()]);",
        "        const outcome = result.Results[0];",
        "        const failed = outcome === undefined || outcome.Status !== ConnectorWriteStatus.Applied;",
        "        if (failed)",
        "        {",
        "            this.ErrorText = outcome?.Reason ?? ConnectorWriteStatus[outcome?.Status ?? ConnectorWriteStatus.Failed];",
        "        }",
        "        else",
        "        {",
        "            this.ErrorText = \"\";",
        "        }",
        "        this.RebuildItems();",
        "        if (!failed)",
        "        {",
        "            const targetId = outcome?.Id ?? savedId;",
        "            this.Selected = this.items.find((row) => row.Id === targetId);",
        "        }",
        "    }",
        "",
        "    private async Delete(): Promise<void>",
        "    {",
        "        if (this.selected === undefined || this.selected.Id === undefined)",
        "        {",
        "            return;",
        "        }",
        "        const result = await this.model.Apply([{ Kind: ConnectorWriteOpKind.Delete, Concept: {Class}VM.Concept, Id: this.selected.Id }]);",
        "        const outcome = result.Results[0];",
        "        this.RebuildItems();",
        "        if (outcome !== undefined && outcome.Status === ConnectorWriteStatus.Applied)",
        "        {",
        "            this.Selected = undefined;",
        "        }",
        "    }",
        "",
        "    // Fired when the model re-materializes (async live load, or an external Refresh).",
        "    // Rebuild the rows, then reconcile Selected: keep an unsaved new row in progress,",
        "    // otherwise re-point to the rebuilt row with the same Id (clearing it if it is gone).",
        "    private OnDataChanged(): void",
        "    {",
        "        const previous = this.selected;",
        "        this.RebuildItems();",
        "        if (previous !== undefined && previous.IsNew)",
        "        {",
        "            return;",
        "        }",
        "        const targetId = previous?.Id;",
        "        this.Selected = targetId === undefined ? undefined : this.items.find((row) => row.Id === targetId);",
        "    }",
        "",
        "    private RebuildItems(): void",
        "    {",
        "        const old = this.items;",
        "        this.items = this.model.Instances({Class}VM.Concept).map((entity) => {Class}VM.FromEntity(entity));",
        "        this.RaisePropertyChanged(\"Items\", old, this.items);",
        "    }",
        "}",
        "",
    ].join(ConceptCrudViewModelGenerator.Eol);

    public readonly Id = ConceptCrudViewModelGenerator.GeneratorId;
    public readonly WritePolicy = WritePolicy.WriteOnce;

    public async Generate(ctx: ConceptGeneratorContext): Promise<GeneratorResult>
    {
        const ui = await ConceptUiGeneratorSupport.LoadModel(ctx);
        const path = ConceptCrudViewModelGenerator.PathTemplate
            .split(ConceptCrudViewModelGenerator.ClassPlaceholder).join(ui.ClassName);
        return ConceptUiGeneratorSupport.WriteOne(ctx, path, this.Render(ui), this.WritePolicy);
    }

    public Render(ui: ConceptUiModel): string
    {
        return ConceptCrudViewModelGenerator.FileTemplate
            .split(ConceptCrudViewModelGenerator.ClassToken).join(ui.ClassName)
            .split(ConceptCrudViewModelGenerator.ConceptToken).join(ui.Concept)
            .split(ConceptCrudViewModelGenerator.SeedsToken).join(this.RenderSeeds(ui.Fields))
            .split(ConceptCrudViewModelGenerator.PropsToken).join(this.RenderProps(ui.Fields))
            .split(ConceptCrudViewModelGenerator.FieldsToken).join(this.RenderFields(ui.Fields));
    }

    private RenderSeeds(fields: readonly UiField[]): string
    {
        if (fields.length === 0)
        {
            return "";
        }
        const seeds = fields
            .map(f => ConceptCrudViewModelGenerator.SeedTemplate
                .split(ConceptCrudViewModelGenerator.NameToken).join(f.Name))
            .join(ConceptCrudViewModelGenerator.Eol);
        return ConceptCrudViewModelGenerator.SnapshotLine + ConceptCrudViewModelGenerator.Eol + seeds;
    }

    private RenderProps(fields: readonly UiField[]): string
    {
        if (fields.length === 0)
        {
            return "";
        }
        return fields
            .map(f => this.PropBlock(f))
            .join(ConceptCrudViewModelGenerator.Eol + ConceptCrudViewModelGenerator.Eol)
            + ConceptCrudViewModelGenerator.Eol;
    }

    private PropBlock(field: UiField): string
    {
        return this.TemplateFor(field.Type)
            .split(ConceptCrudViewModelGenerator.BindingToken).join(field.BindingName)
            .split(ConceptCrudViewModelGenerator.NameToken).join(field.Name);
    }

    private TemplateFor(type: UiFieldType): string
    {
        if (type === UiFieldType.Number)
        {
            return ConceptCrudViewModelGenerator.NumberPropTemplate;
        }
        if (type === UiFieldType.Boolean)
        {
            return ConceptCrudViewModelGenerator.BooleanPropTemplate;
        }
        return ConceptCrudViewModelGenerator.StringPropTemplate;
    }

    private RenderFields(fields: readonly UiField[]): string
    {
        return fields
            .map(f => ConceptCrudViewModelGenerator.FieldEntryTemplate
                .split(ConceptCrudViewModelGenerator.NameToken).join(f.Name)
                .split(ConceptCrudViewModelGenerator.BindingToken).join(f.BindingName))
            .join(ConceptCrudViewModelGenerator.Eol);
    }
}
