import type { IBuildAction } from "../../build-system-core/build-action.js";
import type { TodlBuildContext } from "../todl-build-context.js";
import type { ArtifactKey } from "../../build-system-core/artifact-key.js";
import { Severity } from "../../build-system-core/diagnostic-sink.js";
import { NpmArtifacts } from "../npm/npm-artifacts.js";
import { AppNaming } from "../../project-services/generators/app-naming.js";
import { TenantDocumentAssembler } from "../../../graph-api/browser/tenant-document-assembler.js";
import { RemoteTargetReader } from "./remote-target-reader.js";

// Emits the remote variant of generated/data.ts into the SANDBOX, where it shadows the
// project's snapshot-based one (BundleAppAction.Collect: sandbox wins on collision), so
// the maker's project is untouched. The emitted module is a CONSUMER of the protocol
// (it may import pragmatic-protocol/browser; the engine never does): it defines an
// ITenantReadClient whose ReadDocument runs one `MATCH (n) RETURN n` over the existing
// cypher/query wire method, then assembles a TodlDocument from the build-time ontology
// (embedded here) plus the returned node cells (TenantDocumentAssembler).
export class EmitRemoteDataAction implements IBuildAction<TodlBuildContext>
{
    private static readonly ActionName = "emit-remote-data";
    private static readonly OutputFile = "generated/data.ts";
    private static readonly NoCompiledModelMessage = "no compiled model to embed the remote app schema from";
    private static readonly TenantParam = "tenant";
    private static readonly HttpPrefix = /^http/i;
    private static readonly WsPrefix = "ws";
    private static readonly SchemaToken = "{SCHEMA}";
    private static readonly UrlToken = "{URL}";
    private static readonly AppToken = "{APP}";
    private static readonly DtoToken = "{DTO}";

    private static readonly DataTemplate =
        `// Generated by @pragmatic-tech-ai/todl (remote flavor). Do not edit.\n` +
        `import { BrowserSocketDialer, PragmaticClient } from "@pragmatic-tech-ai/pragmatic-protocol/browser";\n` +
        `import { RemoteTenantConnector, TenantDocumentAssembler, type ITenantReadClient, type TenantNodeCell } from "@pragmatic-tech-ai/todl";\n` +
        `import { {DTO} } from "./model.js";\n` +
        `\n` +
        `class CypherTenantReadClient implements ITenantReadClient\n` +
        `{\n` +
        `    private static readonly Url = {URL};\n` +
        `    private static readonly AppName = {APP};\n` +
        `    private static readonly Query = "MATCH (n) RETURN n";\n` +
        `    private static readonly Schema = {SCHEMA};\n` +
        `\n` +
        `    private client: PragmaticClient | undefined;\n` +
        `\n` +
        `    public async ReadDocument(): ReturnType<ITenantReadClient["ReadDocument"]>\n` +
        `    {\n` +
        `        if (this.client === undefined)\n` +
        `        {\n` +
        `            this.client = await PragmaticClient.ConnectReconnecting(new BrowserSocketDialer(CypherTenantReadClient.Url));\n` +
        `            await this.client.OpenApplication(CypherTenantReadClient.AppName);\n` +
        `        }\n` +
        `        const cells: TenantNodeCell[] = [];\n` +
        `        for await (const page of this.client.QueryAll(CypherTenantReadClient.Query))\n` +
        `        {\n` +
        `            for (const row of page.items)\n` +
        `            {\n` +
        `                for (const cell of row)\n` +
        `                {\n` +
        `                    if (TenantDocumentAssembler.IsNodeCell(cell)) cells.push(cell);\n` +
        `                }\n` +
        `            }\n` +
        `        }\n` +
        `        return TenantDocumentAssembler.Assemble(CypherTenantReadClient.Schema, cells);\n` +
        `    }\n` +
        `}\n` +
        `\n` +
        `export const model = new {DTO}(new RemoteTenantConnector(new CypherTenantReadClient()));\n`;

    public readonly Name = EmitRemoteDataAction.ActionName;
    public readonly Consumes: readonly ArtifactKey<unknown>[] = [NpmArtifacts.CompiledModel];
    public readonly Produces: readonly ArtifactKey<unknown>[] = [];

    public async Execute(ctx: TodlBuildContext): Promise<void>
    {
        const remote = RemoteTargetReader.Read(ctx, EmitRemoteDataAction.ActionName);
        if (remote === undefined) return;
        const compiled = ctx.Artifacts.Get(NpmArtifacts.CompiledModel);
        if (compiled === undefined)
        {
            ctx.Diagnostics.Report({ severity: Severity.Error, message: EmitRemoteDataAction.NoCompiledModelMessage, source: EmitRemoteDataAction.ActionName });
            return;
        }
        const schema = TenantDocumentAssembler.SchemaOf(compiled.fullDocument);
        const source = EmitRemoteDataAction.DataTemplate
            .split(EmitRemoteDataAction.DtoToken).join(AppNaming.DtoClass(ctx.Manifest.id ?? ctx.Manifest.name))
            .split(EmitRemoteDataAction.UrlToken).join(JSON.stringify(EmitRemoteDataAction.WireUrl(remote.ServerUrl, remote.Tenant)))
            .split(EmitRemoteDataAction.AppToken).join(JSON.stringify(remote.AppName))
            .split(EmitRemoteDataAction.SchemaToken).join(JSON.stringify(schema));
        await ctx.Sandbox.WriteText(EmitRemoteDataAction.OutputFile, source);
    }

    // The tenant is selected by the `tenant` query parameter on the server's WebSocket upgrade.
    private static WireUrl(serverUrl: string, tenant: string): string
    {
        const url = new URL(serverUrl.replace(EmitRemoteDataAction.HttpPrefix, EmitRemoteDataAction.WsPrefix));
        url.searchParams.set(EmitRemoteDataAction.TenantParam, tenant);
        return url.toString();
    }
}
