import type { IBuildAction } from "../../build-system-core/build-action.js";
import type { TodlBuildContext } from "../todl-build-context.js";
import type { ArtifactKey } from "../../build-system-core/artifact-key.js";
import { Severity } from "../../build-system-core/diagnostic-sink.js";
import { NpmArtifacts } from "../npm/npm-artifacts.js";
import { AppNaming } from "../../project-services/generators/app-naming.js";
import { TenantDocumentAssembler } from "../../../graph-api/browser/tenant-document-assembler.js";
import { RemoteTargetReader } from "./remote-target-reader.js";

// Emits the remote variant of generated/data.ts into the SANDBOX, where it shadows the
// project's snapshot-based one (BundleAppAction.Collect: sandbox wins on collision), so
// the maker's project is untouched. The emitted module is a CONSUMER of the protocol
// (it may import pragmatic-protocol/browser; the engine never does): it defines an
// ITenantReadClient whose ReadDocument runs one `MATCH (n) RETURN n` over the existing
// cypher/query wire method, then assembles a TodlDocument from the build-time ontology
// (embedded here, typed as TodlDocument) plus the returned node cells (TenantDocumentAssembler).
//
// The socket is same-origin at RUNTIME (derived from `location`): the session cookie
// authenticates it and the server resolves tenant + principal from that cookie, so the
// app sends no tenant. Options.Remote.ServerUrl/Tenant are a dev-only override.
export class EmitRemoteDataAction implements IBuildAction<TodlBuildContext>
{
    private static readonly ActionName = "emit-remote-data";
    private static readonly OutputFile = "generated/data.ts";
    private static readonly NoCompiledModelMessage = "no compiled model to embed the remote app schema from";
    private static readonly BadServerUrlMessage = "remote build Options.Remote.ServerUrl must be a valid http, https, ws or wss URL";
    private static readonly TenantParam = "tenant";
    private static readonly HttpPrefix = /^http/i;
    private static readonly WsPrefix = "ws";
    private static readonly AllowedProtocols: readonly string[] = ["http:", "https:", "ws:", "wss:"];
    private static readonly NoOverride = "null";
    private static readonly SchemaToken = "{SCHEMA}";
    private static readonly UrlToken = "{URL}";
    private static readonly AppToken = "{APP}";
    private static readonly DtoToken = "{DTO}";

    private static readonly DataTemplate =
        `// Generated by @pragmatic-tech-ai/todl (remote flavor). Do not edit.\n` +
        `import { AppWriteOpDto, AppWriteOpKind, AppWriteStatus, BrowserSocketDialer, PragmaticClient, type AppWriteOpResultDto, type AppWriteParams } from "@pragmatic-tech-ai/pragmatic-protocol/browser";\n` +
        `import { ConnectorWriteOpKind, ConnectorWriteStatus, RemoteTenantConnector, TenantDocumentAssembler, type ConnectorWriteOp, type ConnectorWriteOpResult, type ConnectorWriteResult, type ITenantReadClient, type ITenantWriteClient, type TenantNodeCell, type TodlDocument } from "@pragmatic-tech-ai/todl";\n` +
        `import { {DTO} } from "./model.js";\n` +
        `\n` +
        `class CypherTenantClient implements ITenantReadClient, ITenantWriteClient\n` +
        `{\n` +
        `    private static readonly UrlOverride: string | null = {URL};\n` +
        `    private static readonly AppName = {APP};\n` +
        `    private static readonly Query = "MATCH (n) RETURN n";\n` +
        `    private static readonly Schema: TodlDocument = {SCHEMA} as TodlDocument;\n` +
        `\n` +
        `    private client: PragmaticClient | undefined;\n` +
        `\n` +
        `    // Same-origin by default: the page's own origin, so the session cookie authenticates the\n` +
        `    // socket and the server resolves tenant + principal from it. UrlOverride is dev-only.\n` +
        `    private static SocketUrl(): string\n` +
        `    {\n` +
        `        if (CypherTenantClient.UrlOverride !== null) return CypherTenantClient.UrlOverride;\n` +
        `        const scheme = location.protocol === "https:" ? "wss:" : "ws:";\n` +
        `        return scheme + "//" + location.host;\n` +
        `    }\n` +
        `\n` +
        `    private async Connected(): Promise<PragmaticClient>\n` +
        `    {\n` +
        `        if (this.client === undefined)\n` +
        `        {\n` +
        `            this.client = await PragmaticClient.ConnectReconnecting(new BrowserSocketDialer(CypherTenantClient.SocketUrl()));\n` +
        `            await this.client.OpenApplication(CypherTenantClient.AppName);\n` +
        `        }\n` +
        `        return this.client;\n` +
        `    }\n` +
        `\n` +
        `    public async ReadDocument(): ReturnType<ITenantReadClient["ReadDocument"]>\n` +
        `    {\n` +
        `        const client = await this.Connected();\n` +
        `        const cells: TenantNodeCell[] = [];\n` +
        `        for await (const page of client.QueryAll(CypherTenantClient.Query))\n` +
        `        {\n` +
        `            for (const row of page.items)\n` +
        `            {\n` +
        `                for (const cell of row)\n` +
        `                {\n` +
        `                    if (TenantDocumentAssembler.IsNodeCell(cell)) cells.push(cell);\n` +
        `                }\n` +
        `            }\n` +
        `        }\n` +
        `        return TenantDocumentAssembler.Assemble(CypherTenantClient.Schema, cells);\n` +
        `    }\n` +
        `\n` +
        `    private static readonly KindMap: Record<ConnectorWriteOpKind, AppWriteOpKind> =\n` +
        `    {\n` +
        `        [ConnectorWriteOpKind.Create]: AppWriteOpKind.Create,\n` +
        `        [ConnectorWriteOpKind.Update]: AppWriteOpKind.Update,\n` +
        `        [ConnectorWriteOpKind.Delete]: AppWriteOpKind.Delete,\n` +
        `    };\n` +
        `\n` +
        `    private static readonly StatusMap: Record<AppWriteStatus, ConnectorWriteStatus> =\n` +
        `    {\n` +
        `        [AppWriteStatus.Applied]: ConnectorWriteStatus.Applied,\n` +
        `        [AppWriteStatus.Conflict]: ConnectorWriteStatus.Conflict,\n` +
        `        [AppWriteStatus.Denied]: ConnectorWriteStatus.Denied,\n` +
        `        [AppWriteStatus.Invalid]: ConnectorWriteStatus.Invalid,\n` +
        `        [AppWriteStatus.Failed]: ConnectorWriteStatus.Failed,\n` +
        `    };\n` +
        `\n` +
        `    private static ToWireOp(op: ConnectorWriteOp): AppWriteOpDto\n` +
        `    {\n` +
        `        const wire: AppWriteOpDto = { op: CypherTenantClient.KindMap[op.Kind], concept: op.Concept };\n` +
        `        if (op.Id !== undefined) wire.id = op.Id;\n` +
        `        if (op.Fields !== undefined) wire.fields = op.Fields;\n` +
        `        return wire;\n` +
        `    }\n` +
        `\n` +
        `    private static FromWireResult(result: AppWriteOpResultDto): ConnectorWriteOpResult\n` +
        `    {\n` +
        `        const mapped: { Status: ConnectorWriteStatus; Id?: string; Reason?: string } = { Status: CypherTenantClient.StatusMap[result.status] };\n` +
        `        if (result.id !== undefined) mapped.Id = result.id;\n` +
        `        if (result.reason !== undefined) mapped.Reason = result.reason;\n` +
        `        return mapped;\n` +
        `    }\n` +
        `\n` +
        `    public async WriteDocument(ops: readonly ConnectorWriteOp[]): Promise<ConnectorWriteResult>\n` +
        `    {\n` +
        `        const client = await this.Connected();\n` +
        `        const params: AppWriteParams = { operations: ops.map(op => CypherTenantClient.ToWireOp(op)) };\n` +
        `        const response = await client.WriteAppData(params);\n` +
        `        return { Results: response.results.map(r => CypherTenantClient.FromWireResult(r)) };\n` +
        `    }\n` +
        `}\n` +
        `\n` +
        `const client = new CypherTenantClient();\n` +
        `export const model = new {DTO}(new RemoteTenantConnector(client, client));\n`;

    public readonly Name = EmitRemoteDataAction.ActionName;
    public readonly Consumes: readonly ArtifactKey<unknown>[] = [NpmArtifacts.CompiledModel];
    public readonly Produces: readonly ArtifactKey<unknown>[] = [];

    public async Execute(ctx: TodlBuildContext): Promise<void>
    {
        const remote = RemoteTargetReader.Read(ctx, EmitRemoteDataAction.ActionName);
        if (remote === undefined) return;
        const compiled = ctx.Artifacts.Get(NpmArtifacts.CompiledModel);
        if (compiled === undefined)
        {
            ctx.Diagnostics.Report({ severity: Severity.Error, message: EmitRemoteDataAction.NoCompiledModelMessage, source: EmitRemoteDataAction.ActionName });
            return;
        }
        const override = EmitRemoteDataAction.OverrideLiteral(ctx, remote.ServerUrl, remote.Tenant);
        if (override === undefined) return;
        const schema = TenantDocumentAssembler.SchemaOf(compiled.fullDocument);
        const source = EmitRemoteDataAction.DataTemplate
            .split(EmitRemoteDataAction.DtoToken).join(AppNaming.DtoClass(ctx.Manifest.id ?? ctx.Manifest.name))
            .split(EmitRemoteDataAction.UrlToken).join(override)
            .split(EmitRemoteDataAction.AppToken).join(JSON.stringify(remote.AppName))
            .split(EmitRemoteDataAction.SchemaToken).join(JSON.stringify(schema));
        await ctx.Sandbox.WriteText(EmitRemoteDataAction.OutputFile, source);
    }

    // The JSON literal for the dev-only absolute socket URL override, or "null" for the normal
    // same-origin case. A malformed or non-http(s)/ws(s) override is a build error, not a raw TypeError.
    private static OverrideLiteral(ctx: TodlBuildContext, serverUrl: string | undefined, tenant: string | undefined): string | undefined
    {
        if (serverUrl === undefined) return EmitRemoteDataAction.NoOverride;
        const url = EmitRemoteDataAction.TryParse(serverUrl);
        if (url === undefined || !EmitRemoteDataAction.AllowedProtocols.includes(url.protocol))
        {
            ctx.Diagnostics.Report({ severity: Severity.Error, message: EmitRemoteDataAction.BadServerUrlMessage, source: EmitRemoteDataAction.ActionName });
            return undefined;
        }
        if (tenant !== undefined) url.searchParams.set(EmitRemoteDataAction.TenantParam, tenant);
        return JSON.stringify(url.toString());
    }

    private static TryParse(serverUrl: string): URL | undefined
    {
        try
        {
            return new URL(serverUrl.replace(EmitRemoteDataAction.HttpPrefix, EmitRemoteDataAction.WsPrefix));
        }
        catch
        {
            return undefined;
        }
    }
}
